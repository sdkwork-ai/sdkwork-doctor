import { Navigate, Route, Routes } from 'react-router-dom';
import type { AgentConversationPort, CareAgentCatalogPort } from '@sdkwork/doctor-common-agent';
import type { ResolvedAppBlock } from '@sdkwork/doctor-common-blocks';
import type { DoctorRuntimeContext } from '@sdkwork/doctor-common-diagnostics';
import type {
  CareSessionReadStore,
  CareSessionStore,
  DoctorDirectoryPort,
  DoctorSelectionStore,
  MedicalAttachmentStore,
  MedicalRecordStore,
  PatientProfileStore,
  VisitRecordStore,
} from '@sdkwork/doctor-common-doctor';

import {
  CareCallPage,
  ChatPage,
  DevicePage,
  DoctorPage,
  HomePage,
  MePage,
  PatientFilesPage,
  RecordDetailPage,
  RecordsPage,
  useCareAgentCatalog,
  useDoctorRoster,
} from '@sdkwork/doctor-h5-care';

import { MobileShell } from './MobileShell';

export interface DoctorH5RoutesProps {
  readonly runtime: DoctorRuntimeContext;
  readonly hostPlatform: string;
  /** Conversation transport composed once by the app bootstrap. */
  readonly agent: AgentConversationPort;
  /** Device-local visit records shared by chat, landing, and records. */
  readonly records: VisitRecordStore;
  /** 病历 generated by ending a conversation, with both diagnosis records. */
  readonly medicalRecords: MedicalRecordStore;
  /** One conversation session per visit; 看病记录 lists these. */
  readonly careSessions: CareSessionStore;
  /** Read marks behind the unread badges of the conversation list. */
  readonly careSessionReads: CareSessionReadStore;
  /** Attachment bytes for the conversations and the medical records. */
  readonly attachments: MedicalAttachmentStore;
  /** Household patient files (several patients per family). */
  readonly patients: PatientProfileStore;
  /** Device-local selection of human family doctors. */
  readonly selection: DoctorSelectionStore;
  /** Deployment doctor directory with the authored fallback inside. */
  readonly doctorDirectory: DoctorDirectoryPort;
  /** sdkwork-agents catalogue port, used to show the managed agent status. */
  readonly agentCatalog: CareAgentCatalogPort;
  /** Blocks resolved for this surface from the composition contract. */
  readonly blocks: readonly ResolvedAppBlock[];
}

/**
 * Route composition for the H5 surface: the same four tabs as every other
 * client, a workbench landing at `/doctor`, and a `/doctor/me/records` redirect
 * that keeps older links working.
 */
export function DoctorH5Routes({
  runtime,
  agent,
  records,
  medicalRecords,
  careSessions,
  careSessionReads,
  attachments,
  patients,
  selection,
  doctorDirectory,
  agentCatalog,
  blocks,
}: DoctorH5RoutesProps) {
  const rosterState = useDoctorRoster(doctorDirectory);
  const catalogState = useCareAgentCatalog(agentCatalog);

  return (
    <MobileShell appVersion={runtime.appVersion} blocks={blocks} profileId={runtime.profileId}>
      <Routes>
        <Route index element={<HomePage agent={agent} blocks={blocks} careSessions={careSessions} patients={patients} records={records} roster={rosterState.roster} selection={selection} />} />
        <Route path="chat" element={<ChatPage agent={agent} attachments={attachments} careSessionReads={careSessionReads} careSessions={careSessions} medicalRecords={medicalRecords} patients={patients} records={records} />} />
        <Route path="call" element={<CareCallPage agent={agent} careSessions={careSessions} patients={patients} records={records} />} />
        <Route
          path="doctor"
          element={(
            <DoctorPage
              agentMode={agent.mode}
              agents={catalogState.agents}
              careSessions={careSessions}
              patients={patients}
              records={records}
              roster={rosterState.roster}
              rosterLoading={rosterState.loading}
              selection={selection}
            />
          )}
        />
        <Route path="me" element={<MePage agent={agent} careSessions={careSessions} patients={patients} records={records} roster={rosterState.roster} selection={selection} />} />
        <Route path="me/patients" element={<PatientFilesPage patients={patients} />} />
        <Route path="me/device" element={<DevicePage context={runtime} />} />
        <Route
          path="records"
          element={(
            <RecordsPage
              attachments={attachments}
              careSessionReads={careSessionReads}
              careSessions={careSessions}
              medicalRecords={medicalRecords}
              records={records}
              roster={rosterState.roster}
              selection={selection}
            />
          )}
        />
        <Route
          path="records/:recordId"
          element={(
            <RecordDetailPage
              attachments={attachments}
              careSessions={careSessions}
              medicalRecords={medicalRecords}
              roster={rosterState.roster}
              selection={selection}
            />
          )}
        />
        <Route path="me/records" element={<Navigate replace to="/doctor/records" />} />
        <Route path="*" element={<Navigate replace to="/doctor" />} />
      </Routes>
    </MobileShell>
  );
}
