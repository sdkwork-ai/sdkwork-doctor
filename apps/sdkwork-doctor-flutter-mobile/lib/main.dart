/// Agents API base URL injected by the host build; empty selects the offline
/// adapter. The access token is never a build-time value: a host shell injects
/// it after appbase IAM sign-in through [_hostAccessToken].
const String _agentsApiBaseUrl =
    String.fromEnvironment('AGENTS_API_BASE_URL', defaultValue: '');

/// Deployment doctor-directory document URL.
///
/// The browser surfaces read `careDoctorDirectoryUrl` from their runtime-env
/// document (`apps/sdkwork-doctor-h5/config/browser/runtime-env.*.example.json`
/// and the PC equivalent). That document lives outside this app root and is not
/// compiled into the Flutter binary, so this surface receives the same
/// deployment value through the build-time define it already uses for
/// `AGENTS_API_BASE_URL`: pass
/// `--dart-define=CARE_DOCTOR_DIRECTORY_URL=<url>`. Empty means no directory is
/// configured: the authored fallback roster answers and the 医生 tab says so.
const String _careDoctorDirectoryUrl =
    String.fromEnvironment('CARE_DOCTOR_DIRECTORY_URL', defaultValue: '');

Future<void> main() async {
  // The HTTPS trust layer must be installed before any HTTP client is
  // created, so it runs ahead of binding initialization and services.
  SdkworkTlsTrust.installForApp();

  WidgetsFlutterBinding.ensureInitialized();
  final VisitRecordStore records =
      await VisitRecordStore.load(SharedPreferencesVisitRecordStorage());
  final MedicalRecordStore medicalRecords =
      await MedicalRecordStore.load(SharedPreferencesMedicalRecordStorage());
  final CareSessionStore careSessions =
      await CareSessionStore.load(SharedPreferencesCareSessionStorage());
  final PatientProfileStore patients =
      await PatientProfileStore.load(SharedPreferencesPatientProfileStorage());
  final DoctorSelectionStore doctors = await DoctorSelectionStore.load(
      SharedPreferencesDoctorSelectionStorage());
  final CareHumanConsultationStore humanConsultations =
      CareHumanConsultationStore(
    storage: const SharedPreferencesCareHumanConsultationStorage(),
  );
  runApp(DoctorApp(
    records: records,
    medicalRecords: medicalRecords,
    careSessions: careSessions,
    humanConsultations: humanConsultations,
    patients: patients,
    doctors: doctors,
    directory: DoctorDirectory(directoryUrl: _careDoctorDirectoryUrl),
    sessionPinStorage: const SharedPreferencesCareSessionPinStorage(),
  ));
}

class DoctorApp extends StatefulWidget {
  const DoctorApp({
    super.key,
    required this.records,
    this.medicalRecords,
    this.careSessions,
    this.humanConsultations,
    required this.patients,
    required this.doctors,
    this.directory,
    this.conversationService,
    this.sessionPinStorage,
    this.voiceEnvironment,
    this.attachmentPicker,
    this.qrScanEnvironment,
    this.initialLocale,
  });

  /// Device-local consultation history shown by 看病记录.
  final VisitRecordStore records;

  /// Device-local 病历 generated by ending a conversation; null keeps an
  /// in-memory store for tests and previews.
  final MedicalRecordStore? medicalRecords;

  /// One visit session per conversation; 看病记录 lists these. Null keeps an
  /// in-memory store for tests and previews.
  final CareSessionStore? careSessions;

  /// Human consultations held in the conversation home. Null keeps an in-memory
  /// store for tests and previews; the bootstrap supplies shared preferences.
  final CareHumanConsultationStore? humanConsultations;

  /// Device-local household of patient files; the active one supplies the
  /// conversation facts.
  final PatientProfileStore patients;

  /// Device-local selection of the family's human doctors.
  final DoctorSelectionStore doctors;

  /// Deployment doctor directory; null means no directory is configured and
  /// the authored fallback roster answers.
  final DoctorDirectory? directory;

  /// Conversation transport. Null builds one from the compiled deployment
  /// (hosted when an agents API base URL and an IAM token exist, offline
  /// otherwise); tests inject a local service with in-memory storage.
  final CareConversationService? conversationService;

  /// Device-local pinned conversation ids. Null keeps an in-memory store for
  /// tests and previews; the application bootstrap supplies shared preferences.
  final CareSessionPinStorage? sessionPinStorage;

  /// Voice-call platform ports. Null composes the real device ports
  /// (microphone recognition, text-to-speech, camera); tests inject fakes so no
  /// widget test opens a permission dialog or touches a sensor.
  final CareVoiceCallEnvironment? voiceEnvironment;

  /// Conversation attachment picker. Null uses the platform file chooser; tests
  /// inject a fake so no widget test opens a system dialog.
  final CareAttachmentPicker? attachmentPicker;

  /// QR scanner platform environment. Null composes the real camera; tests
  /// inject a fake so no widget test opens the camera or a permission dialog.
  final CareQrScanEnvironment? qrScanEnvironment;

  /// Forces the starting locale (tests and host overrides); otherwise the
  /// platform locale decides.
  final String? initialLocale;

  @override
  State<DoctorApp> createState() => _DoctorAppState();
}

class _DoctorAppState extends State<DoctorApp> {
  late String _locale;
  late final DoctorDirectory _directory;
  late final CareConversationsController _conversations;
  late final MedicalRecordStore _medicalRecords;
  late final CareSessionStore _careSessions;
  late final CareAttachmentPicker _attachmentPicker;

  @override
  void initState() {
    super.initState();
    _locale = resolveCareLocale(
      widget.initialLocale ??
          WidgetsBinding.instance.platformDispatcher.locale.toLanguageTag(),
    );
    _directory = widget.directory ?? DoctorDirectory(directoryUrl: '');
    _medicalRecords = widget.medicalRecords ?? MedicalRecordStore.memory();
    _careSessions = widget.careSessions ?? CareSessionStore.memory();
    _attachmentPicker =
        widget.attachmentPicker ?? const FilePickerCareAttachmentPicker();
    final CareConversationService service = widget.conversationService ??
        createCareConversationService(
          agentsApiBaseUrl: _agentsApiBaseUrl,
          getAccessToken: _hostAccessToken,
          locale: () => _locale,
          localSessionTitle:
              careText(_locale, 'platform.care.sessions.defaultTitle'),
        );
    _conversations = CareConversationsController(
      service: service,
      pinStorage: widget.sessionPinStorage,
      humanStore: widget.humanConsultations,
    );
    // Fire and forget: the drawer renders its own loading and failure states.
    unawaited(_conversations.load());
  }

  /// Replaced by the platform host once IAM sign-in exists; null means offline.
  String? _hostAccessToken() => null;

  @override
  void dispose() {
    _conversations.dispose();
    super.dispose();
  }

  void _toggleLocale() {
    setState(() => _locale = _locale == 'zh-CN' ? 'en-US' : 'zh-CN');
  }

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'SDKWork Doctor',
      theme: buildDoctorTheme(),
      home: DoctorHome(
        locale: _locale,
        conversations: _conversations,
        records: widget.records,
        medicalRecords: _medicalRecords,
        careSessions: _careSessions,
        patients: widget.patients,
        doctors: widget.doctors,
        directory: _directory,
        attachmentPicker: _attachmentPicker,
        voiceEnvironment:
            widget.voiceEnvironment ?? const SystemCareVoiceCallEnvironment(),
        qrScanEnvironment:
            widget.qrScanEnvironment ?? const SystemCareQrScanEnvironment(),
        onToggleLocale: _toggleLocale,
      ),
    );
  }
}

/// The care shell: a session drawer, exactly four destinations (对话 / 医生 /
/// 看病记录 / 我的), and a "+" dropdown menu that starts a consultation, opens
/// the records tab, or scans a QR code.
class DoctorHome extends StatefulWidget {
  const DoctorHome({
    super.key,
    required this.locale,
    required this.conversations,
    required this.records,
    required this.medicalRecords,
    required this.careSessions,
    required this.patients,
    required this.doctors,
    required this.directory,
    required this.attachmentPicker,
    required this.voiceEnvironment,
    required this.qrScanEnvironment,
    required this.onToggleLocale,
  });

  final String locale;
  final CareConversationsController conversations;
  final VisitRecordStore records;
  final MedicalRecordStore medicalRecords;
  final CareSessionStore careSessions;
  final PatientProfileStore patients;
  final DoctorSelectionStore doctors;
  final DoctorDirectory directory;
  final CareAttachmentPicker attachmentPicker;
  final CareVoiceCallEnvironment voiceEnvironment;
  final CareQrScanEnvironment qrScanEnvironment;
  final VoidCallback onToggleLocale;

  @override
  State<DoctorHome> createState() => _DoctorHomeState();
}

class _DoctorHomeState extends State<DoctorHome> {
  int _index = 0;
  late final DoctorRosterController _roster;

  /// 医生 navbar state: the category tab the strip selected.
  String? _doctorCategory;

  static const List<String> _tabLabelKeys = <String>[
    'platform.care.nav.chat',
    'platform.care.nav.doctor',
    'platform.care.nav.records',
    'platform.care.nav.me',
  ];

  @override
  void initState() {
    super.initState();
    _roster = DoctorRosterController(widget.directory);
    _roster.addListener(_pruneSelection);
    _roster.load();
  }

  @override
  void dispose() {
    _roster.removeListener(_pruneSelection);
    _roster.dispose();
    super.dispose();
  }

  /// Drops selected doctor ids that the answered roster no longer carries.
  void _pruneSelection() {
    final DoctorRoster? roster = _roster.roster;
    if (roster == null) return;
    widget.doctors.prune(
      roster.doctors
          .map((DoctorProfile doctor) => doctor.id)
          .toList(growable: false),
    );
  }

  void _openTab(int index) {
    setState(() => _index = index);
  }

  /// Visit records are the third destination, so 我的 and the "+" menu switch
  /// tabs instead of pushing a second copy of the screen.
  void _openRecords() => _openTab(2);

  /// The right-hand "+" menu: one tap opens the dropdown, and the chosen row
  /// switches tabs or opens the scanner.
  void _onMenuAction(CareShellAction action) {
    if (action == CareShellAction.records) {
      _openRecords();
      return;
    }
    if (action == CareShellAction.scan) {
      unawaited(_openScan());
      return;
    }
    unawaited(_startNewConsultation());
  }

  Future<void> _startNewConsultation() async {
    await widget.conversations.createNew();
    if (!mounted) return;
    _openTab(0);
  }

  /// 扫一扫: the screen owns the camera session, closes it after the first QR
  /// code, and shows the decoded content before it returns here.
  Future<void> _openScan() async {
    await Navigator.of(context).push<String>(
      MaterialPageRoute<String>(
        builder: (BuildContext routeContext) => CareScanScreen(
          locale: widget.locale,
          scanner: widget.qrScanEnvironment.createScanner(),
        ),
      ),
    );
  }

  /// The human doctor the open conversation belongs to, or null when it is the
  /// AI family doctor.
  ///
  /// The transport is the authority when it attributes a session to a human
  /// clinician (`CareConversationDoctor.human`). A transport that attributes
  /// nothing keeps the AI doctor, so the household's primary human doctor is the
  /// fallback: that is the clinician the family talks to and who reviews the
  /// 病历.
  String? get _humanDoctorName {
    final CareConversationDoctor attribution =
        widget.conversations.activeSession?.doctor ??
            const CareConversationDoctor.ai();
    if (attribution.isHuman) {
      final String name = attribution.displayName.trim();
      if (name.isNotEmpty) return name;
    }
    final DoctorRoster? roster = _roster.roster;
    if (roster == null) return null;
    final DoctorProfile? primary =
        resolvePrimaryDoctor(roster, widget.doctors.state);
    if (primary == null) return null;
    final String name = primary.displayName.trim();
    return name.isEmpty ? null : name;
  }

  /// Title of the open destination.
  ///
  /// 对话 is a conversation, not a section, so the navbar states who the family
  /// is talking to: the human family doctor's name when one is chosen, and the
  /// tab label otherwise, because the conversation then runs with the AI family
  /// doctor. The other three destinations keep their section label.
  Widget _navbarTitle(String locale) {
    if (_index != 0) {
      return Text(careText(locale, _tabLabelKeys[_index]));
    }
    return AnimatedBuilder(
      animation: Listenable.merge(<Listenable>[
        widget.doctors,
        widget.conversations,
        _roster,
      ]),
      builder: (BuildContext context, Widget? _) => Text(
        _humanDoctorName ?? careText(locale, 'platform.care.nav.chat'),
      ),
    );
  }

  /// Opens the WeChat-style doctor search page. A result pushes the doctor's
  /// detail page on top of search, so back returns to the result list.
  Future<void> _openDoctorSearch() async {
    final DoctorRoster? roster = _roster.roster;
    await Navigator.of(context).push<void>(MaterialPageRoute<void>(
      builder: (BuildContext context) => DoctorSearchScreen(
        locale: widget.locale,
        doctors: roster?.doctors ?? const <DoctorProfile>[],
        conversations: widget.conversations,
        selection: widget.doctors,
        records: widget.records,
        patients: widget.patients,
        onOpenChat: () => _openTab(0),
      ),
    ));
  }

  /// Video-call mode of the active care session: the full-screen call owns the
  /// microphone, the speech engine, and the camera, and every spoken turn lands
  /// in the same transcript and 看病记录 as a typed turn. Both entries — the
  /// navbar action and the 我的 row — open it with the camera already on, like
  /// the H5 chat header.
  Future<void> _openVideoCall() async {
    await Navigator.of(context).push<void>(
      MaterialPageRoute<void>(
        fullscreenDialog: true,
        builder: (BuildContext routeContext) => CareCallScreen(
          locale: widget.locale,
          patient: widget.patients.active,
          environment: widget.voiceEnvironment,
          conversations: widget.conversations,
          initialVideo: true,
          records: widget.records,
          careSessions: widget.careSessions,
        ),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final String locale = widget.locale;
    return Scaffold(
      appBar: AppBar(
        centerTitle: true,
        leading: Builder(
          builder: (BuildContext buttonContext) => IconButton(
            tooltip: careText(locale, 'platform.care.nav.menu'),
            icon: const Icon(Icons.menu),
            onPressed: () => Scaffold.of(buttonContext).openDrawer(),
          ),
        ),
        title: _navbarTitle(locale),
        actions: <Widget>[
          // The video call sits left of the "+" so the two chat actions read as
          // "call" then "more". It opens with the camera on, matching the 我的
          // row and the H5 chat header, so the icon and the call agree.
          IconButton(
            tooltip: careText(locale, 'platform.care.call.videoTitle'),
            icon: const Icon(Icons.videocam_outlined),
            onPressed: _openVideoCall,
          ),
          CareActionMenu(locale: locale, onSelected: _onMenuAction),
          // 医生 is the searchable directory: the navbar search icon opens the
          // search page, and the category tabs sit in the navbar bottom.
          if (_index == 1)
            IconButton(
              tooltip: careText(locale, 'platform.care.doctors.searchAction'),
              icon: const Icon(Icons.search),
              onPressed: _openDoctorSearch,
            ),
        ],
        bottom: _index == 1
            ? PreferredSize(
                preferredSize: const Size.fromHeight(44),
                child: DoctorCategoryBar(
                  locale: locale,
                  doctors: _roster.roster?.doctors ?? const <DoctorProfile>[],
                  selected: _doctorCategory,
                  onSelected: (String? key) =>
                      setState(() => _doctorCategory = key),
                ),
              )
            : null,
      ),
      drawer: CareSessionsDrawer(
        controller: widget.conversations,
        agentName: 'SDKWork Doctor',
        style: doctorSessionsDrawerStyle,
        translate: (String key,
                {Map<String, String> params = const <String, String>{}}) =>
            careText(locale, key, params: params),
        onSelected: (CareConversationSession session) => _openTab(0),
      ),
      body: IndexedStack(
        index: _index,
        children: <Widget>[
          ChatTab(
            locale: locale,
            conversations: widget.conversations,
            records: widget.records,
            medicalRecords: widget.medicalRecords,
            careSessions: widget.careSessions,
            patients: widget.patients,
            attachmentPicker: widget.attachmentPicker,
            onOpenMe: () => _openTab(3),
          ),
          DoctorTab(
            locale: locale,
            conversations: widget.conversations,
            mode: widget.conversations.mode,
            patients: widget.patients,
            records: widget.records,
            selection: widget.doctors,
            roster: _roster,
            category: _doctorCategory,
            onOpenChat: () => _openTab(0),
          ),
          RecordsScreen(
            locale: locale,
            records: widget.records,
            medicalRecords: widget.medicalRecords,
            careSessions: widget.careSessions,
            voiceEnvironment: widget.voiceEnvironment,
            roster: _roster.roster,
            selection: widget.doctors,
          ),
          MeTab(
            locale: locale,
            agentMode: widget.conversations.mode,
            records: widget.records,
            careSessions: widget.careSessions,
            patients: widget.patients,
            selection: widget.doctors,
            roster: _roster,
            onOpenChat: () => _openTab(0),
            onOpenVideoCall: _openVideoCall,
            onOpenDoctors: () => _openTab(1),
            onOpenRecords: _openRecords,
            onToggleLocale: widget.onToggleLocale,
          ),
        ],
      ),
      bottomNavigationBar: NavigationBar(
        selectedIndex: _index,
        onDestinationSelected: _openTab,
        destinations: <NavigationDestination>[
          NavigationDestination(
            icon: const Icon(Icons.chat_bubble_outline),
            selectedIcon: const Icon(Icons.chat_bubble),
            label: careText(locale, 'platform.care.nav.chat'),
          ),
          NavigationDestination(
            icon: const Icon(Icons.medical_information_outlined),
            selectedIcon: const Icon(Icons.medical_information),
            label: careText(locale, 'platform.care.nav.doctor'),
          ),
          NavigationDestination(
            icon: const Icon(Icons.receipt_long_outlined),
            selectedIcon: const Icon(Icons.receipt_long),
            label: careText(locale, 'platform.care.nav.records'),
          ),
          NavigationDestination(
            icon: const Icon(Icons.person_outline),
            selectedIcon: const Icon(Icons.person),
            label: careText(locale, 'platform.care.nav.me'),
          ),
        ],
      ),
    );
  }
}
