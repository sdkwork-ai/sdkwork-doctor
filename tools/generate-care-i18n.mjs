#!/usr/bin/env node
/**
 * Generate the care-surface i18n catalogs from the hand-authored source
 * contract. Every output carries a generated banner; edits belong in
 * apps/sdkwork-doctor-common/packages/sdkwork-doctor-common-doctor/contracts/care-messages.json
 * followed by re-running this tool.
 *
 * Targets: the two React care packages (PC, H5), the Flutter assets, and the
 * WeChat mini program asset. One source keeps four clients on one vocabulary.
 */
import fs from 'node:fs';
import path from 'node:path';

const repoRoot = path.resolve(import.meta.dirname, '..');
const sourcePath = path.join(
  repoRoot,
  'apps/sdkwork-doctor-common/packages/sdkwork-doctor-common-doctor/contracts/care-messages.json',
);
const reactPackages = [
  ['apps/sdkwork-doctor-pc/packages/sdkwork-doctor-pc-care', 'doctorCareI18n'],
  ['apps/sdkwork-doctor-h5/packages/sdkwork-doctor-h5-care', 'doctorCareI18n'],
];
const dartOutput = 'apps/sdkwork-doctor-flutter-mobile/lib/i18n/care_messages.dart';
const miniProgramOutput = 'apps/sdkwork-doctor-mini-program/src/lib/care-i18n.js';

const source = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));
const locales = source.locales;
const banner = '// @generated by tools/generate-care-i18n.mjs from contracts/care-messages.json - do not edit.';

function ensureParent(relativePath) {
  fs.mkdirSync(path.dirname(path.join(repoRoot, relativePath)), { recursive: true });
}

function write(relativePath, body) {
  ensureParent(relativePath);
  fs.writeFileSync(path.join(repoRoot, relativePath), body, 'utf8');
}

/** Dart single-quoted literal: escapes backslash, quote, interpolation, and newlines. */
function dartString(value) {
  return "'" + value
    .replaceAll('\\', '\\\\')
    .replaceAll("'", "\\'")
    .replaceAll('$', '\\$')
    .replaceAll('\n', '\\n') + "'";
}

for (const [rel, exportName] of reactPackages) {
  for (const locale of locales) {
    const entries = source.messages.map((message) => [message.key, message[locale]]);
    const body = banner + '\n'
      + 'export const messages = {\n'
      + entries.map(([key, value]) => '  ' + JSON.stringify(key) + ': ' + JSON.stringify(value) + ',').join('\n')
      + '\n};\n';
    write(path.join(rel, 'src', 'i18n', locale, 'platform', 'care', 'care.ts'), body);
  }
  const imports = locales.map((locale) => "import { messages as " + locale.replace('-', '') + " } from './" + locale + "/platform/care/care';").join('\n');
  const indexBody = banner + '\n' + imports
    + '\n\nexport const ' + exportName + " = Object.freeze({\n"
    + locales.map((locale) => "  '" + locale + "': " + locale.replace('-', '') + ",").join('\n')
    + '\n});\n';
  write(path.join(rel, 'src', 'i18n', 'index.ts'), indexBody);
  console.log('generated ' + rel);
}

const dartBody = banner + '\n'
  + '/// Locales shipped by the care catalog.\n'
  + 'const List<String> careLocales = <String>[' + locales.map(dartString).join(', ') + '];\n\n'
  + '/// Care copy per locale, projected from contracts/care-messages.json.\n'
  + 'const Map<String, Map<String, String>> careMessages = <String, Map<String, String>>{\n'
  + locales.map((locale) => '  ' + dartString(locale) + ': <String, String>{\n'
    + source.messages.map((message) => '    ' + dartString(message.key) + ': ' + dartString(message[locale]) + ',').join('\n')
    + '\n  },').join('\n')
  + '\n};\n';
write(dartOutput, dartBody);
console.log('generated ' + dartOutput);

const miniProgramBody = banner + '\n'
  + 'module.exports = Object.freeze({\n'
  + '  locales: ' + JSON.stringify(locales) + ',\n'
  + '  messages: {\n'
  + locales.map((locale) => '    ' + JSON.stringify(locale) + ': {\n'
    + source.messages.map((message) => '      ' + JSON.stringify(message.key) + ': ' + JSON.stringify(message[locale]) + ',').join('\n')
    + '\n    },').join('\n')
  + '\n  },\n'
  + '});\n';
write(miniProgramOutput, miniProgramBody);
console.log('generated ' + miniProgramOutput);
