#!/usr/bin/env node
/**
 * Generate the care-surface i18n fragments from the hand-authored source
 * contract. The TypeScript files under src/i18n/** are projections and carry a
 * generated banner; edits belong in
 * apps/sdkwork-doctor-common/packages/sdkwork-doctor-common-doctor/contracts/care-messages.json
 * followed by re-running this tool.
 */
import fs from 'node:fs';
import path from 'node:path';

const repoRoot = path.resolve(import.meta.dirname, '..');
const sourcePath = path.join(
  repoRoot,
  'apps/sdkwork-doctor-common/packages/sdkwork-doctor-common-doctor/contracts/care-messages.json',
);
const packages = [
  ['apps/sdkwork-doctor-pc/packages/sdkwork-doctor-pc-care', 'doctorCareI18n'],
  ['apps/sdkwork-doctor-h5/packages/sdkwork-doctor-h5-care', 'doctorCareI18n'],
];

const source = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));
const locales = source.locales;

for (const [rel, exportName] of packages) {
  const base = path.join(repoRoot, rel, 'src', 'i18n');
  for (const locale of locales) {
    const entries = source.messages.map((message) => [message.key, message[locale]]);
    const body = '// @generated by tools/generate-care-i18n.mjs from contracts/care-messages.json - do not edit.\n'
      + 'export const messages = {\n'
      + entries.map(([key, value]) => '  ' + JSON.stringify(key) + ': ' + JSON.stringify(value) + ',').join('\n')
      + '\n};\n';
    const file = path.join(base, locale, 'platform', 'care', 'care.ts');
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, body, 'utf8');
  }
  const imports = locales.map((locale) => "import { messages as " + locale.replace('-', '') + " } from './" + locale + "/platform/care/care';").join('\n');
  const indexBody = '// @generated by tools/generate-care-i18n.mjs - do not edit.\n' + imports
    + '\n\nexport const ' + exportName + " = Object.freeze({\n"
    + locales.map((locale) => "  '" + locale + "': " + locale.replace('-', '') + ",").join('\n')
    + '\n});\n';
  fs.writeFileSync(path.join(base, 'index.ts'), indexBody, 'utf8');
  console.log('generated ' + rel);
}
