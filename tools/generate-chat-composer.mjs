#!/usr/bin/env node
/**
 * Project the shared SDKWork mini program conversation composer into this
 * repository's mini program source tree.
 *
 * WeChat resolves custom component files from the project tree at build time,
 * so the shared appbase component is vendored as a generated projection instead
 * of a runtime dependency. The source of truth stays in appbase:
 *   ../sdkwork-appbase/packages/mini-program/foundation/sdkwork-chat-composer-mini-program
 *
 * Usage:
 *   node tools/generate-chat-composer.mjs          write the projection
 *   node tools/generate-chat-composer.mjs --check  fail when the projection drifted
 */
import fs from 'node:fs';
import path from 'node:path';

const repoRoot = path.resolve(import.meta.dirname, '..');
const SOURCE_LABEL =
  'sdkwork-appbase/packages/mini-program/foundation/sdkwork-chat-composer-mini-program/src/components/chat-composer';
const SOURCE = path.resolve(repoRoot, '..', SOURCE_LABEL);
const TARGET = path.join(
  repoRoot,
  'apps/sdkwork-doctor-mini-program/src/components/chat-composer',
);
const FILES = ['index.js', 'index.json', 'index.wxml', 'index.wxss'];

/** Comment banner for the file types that support comments; JSON does not. */
function bannerFor(file) {
  if (file.endsWith('.js')) {
    return `// @generated by tools/generate-chat-composer.mjs from ${SOURCE_LABEL} - do not edit.\n`;
  }
  if (file.endsWith('.wxml')) {
    return `<!-- @generated by tools/generate-chat-composer.mjs from ${SOURCE_LABEL} - do not edit. -->\n`;
  }
  if (file.endsWith('.wxss')) {
    return `/* @generated by tools/generate-chat-composer.mjs from ${SOURCE_LABEL} - do not edit. */\n`;
  }
  return '';
}

/** Renders every projected file from the shared appbase source. */
export function renderChatComposerProjection() {
  if (!fs.existsSync(SOURCE)) {
    throw new Error(`shared composer source is missing: ${SOURCE}`);
  }
  return FILES.map((file) => {
    const sourceFile = path.join(SOURCE, file);
    if (!fs.existsSync(sourceFile)) {
      throw new Error(`shared composer file is missing: ${sourceFile}`);
    }
    return { file, content: bannerFor(file) + fs.readFileSync(sourceFile, 'utf8') };
  });
}

/** Returns one message per missing or drifted projected file. */
export function checkChatComposerProjection() {
  const issues = [];
  for (const { file, content } of renderChatComposerProjection()) {
    const targetFile = path.join(TARGET, file);
    if (!fs.existsSync(targetFile)) {
      issues.push(`missing ${path.relative(repoRoot, targetFile)}`);
      continue;
    }
    if (fs.readFileSync(targetFile, 'utf8') !== content) {
      issues.push(`drifted ${path.relative(repoRoot, targetFile)}`);
    }
  }
  return issues;
}

function writeProjection() {
  fs.mkdirSync(TARGET, { recursive: true });
  for (const { file, content } of renderChatComposerProjection()) {
    const targetFile = path.join(TARGET, file);
    fs.writeFileSync(targetFile, content, 'utf8');
    console.log(`wrote ${path.relative(repoRoot, targetFile)}`);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  if (process.argv.includes('--check')) {
    const issues = checkChatComposerProjection();
    if (issues.length > 0) {
      console.error('chat composer projection drifted; run node tools/generate-chat-composer.mjs');
      for (const issue of issues) console.error(`- ${issue}`);
      process.exit(1);
    }
    console.log('chat composer projection is current');
  } else {
    writeProjection();
  }
}
