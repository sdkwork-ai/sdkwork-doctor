import assert from 'node:assert/strict';
import { test } from 'node:test';
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';

const require = createRequire(import.meta.url);
const repoRoot = path.resolve(import.meta.dirname, '..');
const sourcePath = path.join(repoRoot, 'apps/sdkwork-doctor-common/packages/sdkwork-doctor-common-doctor/contracts/care-messages.json');
const source = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));
const miniProgramCatalog = require(path.join(repoRoot, 'apps/sdkwork-doctor-mini-program/src/lib/care-i18n.js'));

/** Parses the generated Dart catalog: locale blocks of 4-space `'key': 'value',` lines. */
function parseDartCatalog(file) {
  const text = fs.readFileSync(file, 'utf8');
  assert.match(text, /@generated by tools\/generate-care-i18n\.mjs/u, file + ' must carry the generated banner');
  const catalog = new Map();
  let current = null;
  for (const line of text.split(/\r?\n/u)) {
    const localeMatch = /^  '([a-z]{2}-[A-Z]{2})': <String, String>\{$/u.exec(line);
    if (localeMatch) {
      current = new Map();
      catalog.set(localeMatch[1], current);
      continue;
    }
    const entry = /^    '((?:[^'\\]|\\.)*)': '((?:[^'\\]|\\.)*)',$/u.exec(line);
    if (entry && current) {
      current.set(
        entry[1].replace(/\\'/gu, "'"),
        entry[2].replace(/\\\$/gu, '$').replace(/\\'/gu, "'").replace(/\\\\/gu, '\\'),
      );
    }
  }
  return catalog;
}

function entriesOf(file) {
  const text = fs.readFileSync(file, 'utf8');
  assert.match(text, /@generated by tools\/generate-care-i18n\.mjs/u, file + ' must carry the generated banner');
  const entries = new Map();
  for (const match of text.matchAll(/^  ("(?:[^"\\]|\\.)*"): ("(?:[^"\\]|\\.)*"),$/gmu)) {
    entries.set(JSON.parse(match[1]), JSON.parse(match[2]));
  }
  return entries;
}

test('generated care catalogs match the authored source contract', () => {
  const expected = new Map(source.messages.map((message) => [message.key, message]));
  for (const pkg of ['sdkwork-doctor-pc/packages/sdkwork-doctor-pc-care', 'sdkwork-doctor-h5/packages/sdkwork-doctor-h5-care']) {
    for (const locale of source.locales) {
      const file = path.join(repoRoot, 'apps', pkg, 'src/i18n', locale, 'platform', 'care', 'care.ts');
      const entries = entriesOf(file);
      assert.equal(entries.size, expected.size, file + ' key count drifted; re-run tools/generate-care-i18n.mjs');
      for (const [key, message] of expected) {
        assert.equal(entries.get(key), message[locale], file + ' value drifted for ' + key);
      }
    }
  }
});

test('every care placeholder is preserved in both locales', () => {
  for (const locale of source.locales) {
    for (const message of source.messages) {
      const placeholders = [...String(message['en-US']).matchAll(/\{\{(\w+)\}\}/gu)].map((match) => match[1]).sort();
      const localized = [...String(message[locale]).matchAll(/\{\{(\w+)\}\}/gu)].map((match) => match[1]).sort();
      assert.deepEqual(localized, placeholders, message.key + ' (' + locale + ') placeholder mismatch');
    }
  }
});

test('the Flutter catalog matches the authored source contract', () => {
  const dartPath = path.join(repoRoot, 'apps/sdkwork-doctor-flutter-mobile/lib/i18n/care_messages.dart');
  const catalog = parseDartCatalog(dartPath);
  assert.deepEqual([...catalog.keys()], source.locales, dartPath);
  assert.equal(catalog.size, source.locales.length);
  for (const locale of source.locales) {
    const entries = catalog.get(locale);
    assert.equal(entries.size, source.messages.length, 'Dart key count drifted; re-run tools/generate-care-i18n.mjs');
    for (const message of source.messages) {
      assert.equal(entries.get(message.key), message[locale], 'Dart value drifted for ' + locale + '/' + message.key);
    }
  }
});

test('the mini program catalog matches the authored source contract', () => {
  assert.deepEqual(miniProgramCatalog.locales, source.locales);
  for (const locale of source.locales) {
    const entries = miniProgramCatalog.messages[locale];
    assert.equal(Object.keys(entries).length, source.messages.length, 'mini program key count drifted');
    for (const message of source.messages) {
      assert.equal(entries[message.key], message[locale], 'mini program value drifted for ' + locale + '/' + message.key);
    }
  }
});
