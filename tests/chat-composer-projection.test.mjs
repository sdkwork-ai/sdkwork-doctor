import assert from 'node:assert/strict';
import { test } from 'node:test';
import fs from 'node:fs';
import path from 'node:path';

import {
  checkChatComposerProjection,
  renderChatComposerProjection,
} from '../tools/generate-chat-composer.mjs';

const repoRoot = path.resolve(import.meta.dirname, '..');
const miniProgramRoot = path.join(repoRoot, 'apps/sdkwork-doctor-mini-program');
const read = (relativePath) => fs.readFileSync(path.join(repoRoot, relativePath), 'utf8');

test('the mini program composer projection is current', () => {
  assert.deepEqual(
    checkChatComposerProjection(),
    [],
    'run node tools/generate-chat-composer.mjs after changing the appbase component',
  );
});

test('every comment-capable projected composer file carries its generated banner', () => {
  for (const { content, file } of renderChatComposerProjection()) {
    if (file.endsWith('.json')) {
      continue;
    }
    assert.match(
      content,
      /@generated by tools\/generate-chat-composer\.mjs/u,
      file + ' must carry the generated banner',
    );
  }
});

test('the projected component keeps the shared event and property contract', () => {
  const manifest = JSON.parse(
    fs.readFileSync(path.join(miniProgramRoot, 'src/components/chat-composer/index.json'), 'utf8'),
  );
  assert.equal(manifest.component, true);

  const definition = read('apps/sdkwork-doctor-mini-program/src/components/chat-composer/index.js');
  for (const property of [
    'attachEnabled',
    'attachLabel',
    'busy',
    'disabled',
    'modeLabel',
    'modeSelectable',
    'placeholder',
    'sendLabel',
    'value',
    'voiceEnabled',
    'voiceLabel',
  ]) {
    assert.match(definition, new RegExp(`\\b${property}: \\{`, 'u'), 'definition must declare ' + property);
  }
  for (const trigger of [
    'attach',
    'input',
    'modeTap',
    'send',
    'voiceEnd',
    'voiceStart',
  ]) {
    assert.match(definition, new RegExp(`triggerEvent\\('${trigger}'`, 'u'), 'definition must emit ' + trigger);
  }

  const wxml = read('apps/sdkwork-doctor-mini-program/src/components/chat-composer/index.wxml');
  for (const binding of ['attachLabel', 'disabled', 'modeLabel', 'placeholder', 'sendLabel', 'draft', 'voiceLabel']) {
    assert.match(wxml, new RegExp(`\\{\\{${binding}\\}\\}`, 'u'), 'wxml must consume ' + binding);
  }
  for (const handler of ['onInput', 'onConfirm', 'onVoiceStart', 'onVoiceEnd', 'onAttach', 'onModeTap', 'submit']) {
    assert.match(wxml, new RegExp(`"${handler}"`, 'u'), 'wxml must bind ' + handler);
  }
});

test('the conversation page declares and binds the shared composer', () => {
  const manifest = JSON.parse(
    read('apps/sdkwork-doctor-mini-program/src/pages/conversation/index.json'),
  );
  assert.equal(
    manifest.usingComponents['chat-composer'],
    '/components/chat-composer/index',
  );

  const wxml = read('apps/sdkwork-doctor-mini-program/src/pages/conversation/index.wxml');
  assert.match(wxml, /<chat-composer/u);
  assert.match(wxml, /bind:send="onSend"/u);
  assert.match(wxml, /bind:input="onInput"/u);
  assert.match(wxml, /mode-label="\{\{modeLabel\}\}"/u);
  assert.doesNotMatch(wxml, /<input\b/u, 'the inline composer was replaced by the shared component');
});

test('the mini program copies no composer implementation of its own', () => {
  const componentSource = read('apps/sdkwork-doctor-mini-program/src/components/chat-composer/index.js');
  assert.match(componentSource, /@generated/u, 'the local copy is a projection, not an authored fork');
});
